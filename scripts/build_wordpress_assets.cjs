const fs = require('node:fs');
const path = require('node:path');
const { buildSync } = require('esbuild');

const root = path.resolve(__dirname, '..');
const bundles = [
  { assets: 'wordpress-plugin/ehrman-blog-discovery/assets', name: 'discovery' },
  { assets: 'wordpress-demo-plugins/ehrman-reviewer-tools/assets', name: 'reviewer' },
];

function compileAssets({ productionOnly = false } = {}) {
  const selected = bundles.filter(bundle => bundle.name === 'discovery'
    || (!productionOnly && fs.existsSync(path.join(root, bundle.assets))));
  return selected.flatMap(({ assets, name }) => ['js', 'css'].map(type => {
    const result = buildSync({
      absWorkingDir: root,
      entryPoints: [`${assets}/src/${type}/${name}.${type}`],
      outfile: `${assets}/${type}/${name}.${type}`,
      bundle: true,
      write: false,
      metafile: true,
      minify: false,
      treeShaking: name === 'reviewer',
      charset: 'ascii',
      legalComments: 'none',
      target: 'es2020',
      // Keep PDF newline/trailing-space bytes escaped, not literal whitespace in the bundle.
      ...(type === 'js' ? { format: 'iife', supported: { 'template-literal': false }, banner: { js: '/* Generated by npm run build:wordpress-assets. Edit assets/src/js instead. */\n"use strict";' } }
        : { banner: { css: '/* Generated by npm run build:wordpress-assets. Edit assets/src/css instead. */' } }),
    });
    if (result.warnings.length) throw new Error(`Resolve ${type} asset warnings before building.`);
    return result;
  }));
}

function main() {
  const check = process.argv.includes('--check');
  // Compile all assets before writing any, so syntax failures leave them intact.
  const results = compileAssets({ productionOnly: process.argv.includes('--production-only') });
  for (const result of results) {
    for (const file of result.outputFiles) {
      const relative = path.relative(root, file.path);
      if (check) {
        const existing = fs.readFileSync(file.path, 'utf8').replace(/\r\n/g, '\n');
        if (existing !== file.text) throw new Error(`${relative} is stale. Run npm run build:wordpress-assets.`);
      } else {
        fs.mkdirSync(path.dirname(file.path), { recursive: true });
        fs.writeFileSync(file.path, file.contents);
      }
      console.log(`${check ? 'Verified' : 'Built'} ${relative}`);
    }
  }
}

module.exports = { compileAssets };
if (require.main === module) main();
